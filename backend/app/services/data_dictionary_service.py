def get_all_canonical_contracts() -> list[dict[str, Any]]:
    """Returns a list of all canonical enterprise contracts."""
    return list(CANONICAL_DATA_CONTRACTS.values())


def get_contract_for_entity(entity_type: str) -> dict[str, Any] | None:
    """Retrieves the canonical contract for a given entity type (case-insensitive)."""
    return CANONICAL_DATA_CONTRACTS.get(entity_type.upper())


def resolve_field_aliases(entity_type: str) -> dict[str, list[str]]:
    """Extracts field aliases dict for dynamic column mapping."""
    contract = get_contract_for_entity(entity_type)
    if not contract:
        return {}
    return {f["field_name"]: f["aliases"] for f in contract["fields"]}
